"""Writes the palette role table into THEMES.md, between <!-- roles:start --> and <!-- roles:end -->.

Roles and their meanings come from the @param lines of Palette.java, examples from the bedrock chroma,
readers from the p.<role>() calls under core, contrast floors from the Ink.readable calls. Exits non-zero
when a role has no meaning line, or when a chroma names a key that is not a role.

    python tools/palette_roles.py [--check]
"""
import json
import pathlib
import re
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
SRC = ROOT / "core/src/main/java/dev/dryaides/minuit"
CHROMAS = ROOT / "core/src/main/resources/assets/minuit/minuit/chromas"
DOC = ROOT / "THEMES.md"
START, END = "<!-- roles:start -->", "<!-- roles:end -->"
MAX_READERS = 6
NOT_ROLES = {"series"}  # chart series list, see "Chart series colours"

# Floors set by Ink beyond the Ink.readable calls the scan finds.
INK_RULES = {
    "text": "4.5:1 on its face; Ink.on picks it or flips to the far ink",
    "textSoft": "4.5:1 on its face, else Ink.soft falls back to Ink.on",
    "disabledText": "raised to 3:1 on its face (Ink.disabled)",
}
FLOORS = {"TEXT": "4.5:1 as text", "MARK": "3:1 as a mark"}


def fail(msg):
    sys.exit("palette_roles: " + msg)


def roles_and_meanings():
    java = (SRC / "Palette.java").read_text(encoding="utf-8")
    head = re.search(r"public record Palette\(([^)]*)\)", java)
    if not head:
        fail("no record header in Palette.java")
    roles = re.findall(r"int\s+(\w+)", head.group(1))
    doc = java[:head.start()]
    meanings, current = {}, None
    for line in doc.splitlines():
        body = line.strip().lstrip("/*").strip()
        m = re.match(r"@param\s+(\w+)\s+(.*)", body)
        if m:
            current = m.group(1)
            meanings[current] = m.group(2).strip()
        elif current and body and not body.startswith("@"):
            meanings[current] += " " + body
        else:
            current = None
    missing = [r for r in roles if not meanings.get(r)]
    if missing:
        fail("roles with no @param meaning in Palette.java: " + ", ".join(missing))
    clean = {r: re.sub(r"\{@link #?(\w+)\(?\)?\}", r"`\1`", meanings[r]) for r in roles}
    return roles, clean


def check_chromas(roles):
    for f in sorted(CHROMAS.glob("*.json")):
        for name, variant in json.loads(f.read_text(encoding="utf-8")).get("variants", {}).items():
            extra = sorted(set(variant) - set(roles) - NOT_ROLES)
            if extra:
                fail(f"{f.name} {name} sets keys that are not roles: {', '.join(extra)}")


def readers_and_floors(roles):
    readers = {r: set() for r in roles}
    floors = {r: set() for r in roles}
    call = re.compile(r"\bp\.(\w+)\(\)")
    readable = re.compile(r"Ink\.readable\(p\.(\w+)\(\)[^;]*?Ink\.(TEXT|MARK)\)")
    for f in sorted(SRC.glob("*.java")):
        if f.name == "Palette.java":
            continue
        text = f.read_text(encoding="utf-8")
        for role in set(call.findall(text)) & set(roles):
            readers[role].add(f.stem)
        for role, floor in readable.findall(text):
            if role in floors:
                floors[role].add(FLOORS[floor])
    return readers, floors


def swatch(variant, role):
    v = variant.get(role)
    return f"`{v}`" if v else "unset"


def table(roles, meanings):
    bedrock = json.loads((CHROMAS / "bedrock.json").read_text(encoding="utf-8"))["variants"]
    readers, floors = readers_and_floors(roles)
    rows = ["| Role | What it colours | Bedrock light | Bedrock dark | Read by | Contrast rule |",
            "|---|---|---|---|---|---|"]
    for r in roles:
        names = sorted(n[:-9] if n.endswith("Component") else n for n in readers[r])
        shown = ", ".join(names[:MAX_READERS]) + (f", +{len(names) - MAX_READERS} more" if len(names) > MAX_READERS else "")
        rules = [INK_RULES[r]] if r in INK_RULES else []
        if floors[r]:
            rules.append("Ink.readable raises it to " + " or ".join(sorted(floors[r])) + " where it is drawn as one")
        rows.append(f"| `{r}` | {meanings[r].replace('|', '/')} | {swatch(bedrock.get('light', {}), r)} | "
                    f"{swatch(bedrock.get('dark', {}), r)} | {shown or 'none'} | {'; '.join(rules) or '-'} |")
    return "\n".join(rows)


def main():
    roles, meanings = roles_and_meanings()
    check_chromas(roles)
    raw = DOC.read_bytes().decode("utf-8")
    nl = "\r\n" if "\r\n" in raw else "\n"
    if raw.count(START) != 1 or raw.count(END) != 1:
        fail(f"THEMES.md needs one {START} and one {END}")
    before, rest = raw.split(START)
    _, after = rest.split(END)
    block = (nl + "Generated by `tools/palette_roles.py` from `Palette.java`, the chromas and the code that reads "
             "each role. Edit the @param line in `Palette.java`, then run the script." + nl + nl
             + table(roles, meanings).replace("\n", nl) + nl)
    out = before + START + block + END + after
    if "--check" in sys.argv:
        if out != raw:
            fail("THEMES.md role table is out of date; run tools/palette_roles.py")
        return
    DOC.write_bytes(out.encode("utf-8"))
    print(f"{len(roles)} roles written to {DOC.name}")


if __name__ == "__main__":
    main()
